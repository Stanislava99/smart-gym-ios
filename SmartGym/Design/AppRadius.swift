import SwiftUI

enum AppRadius {
    /// 999px - Pills, nav items, full-round buttons
    static let pill: CGFloat = 999

    /// 24–28px - Large feature cards
    static let xl: CGFloat = 26

    /// 18–22px - Standard cards
    static let lg: CGFloat = 20

    /// 14–16px - Smaller cards, list containers
    static let md: CGFloat = 15

    /// 10–12px - Badges, chips, small controls
    static let sm: CGFloat = 11

    /// 8px - Nested labels
    static let xs: CGFloat = 8
}
